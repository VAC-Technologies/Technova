# --- SSL / TLS configuration ------------------------------------------------
# DB_SSL_CA : absolute path to the CA certificate PEM file.
#   TiDB Cloud Starter requires SSL. Supply the ISRG Root X1 cert path.
#   If left blank the driver falls back to certifi bundle validation.
# DB_SSL_VERIFY_CERT : set to 'false' only for local testing without a cert;
#   always leave 'true' (default) in staging and production.
_ssl_ca = os.getenv('DB_SSL_CA', '')
_ssl_verify = os.getenv('DB_SSL_VERIFY_CERT', 'true').lower() != 'false'

_db_options: dict = {'charset': 'utf8mb4'}
if _ssl_ca:
    # PyMySQL accepts an ssl dict with 'ca' key (maps to ssl_ca).
    _db_options['ssl'] = {'ca': _ssl_ca}
elif _ssl_verify:
    # No explicit CA path — use certifi bundle so TiDB Cloud Let's Encrypt
    # chain (signed by ISRG Root X1) is still validated.
    try:
        import certifi as _certifi
        _db_options['ssl'] = {'ca': _certifi.where()}
    except ImportError:
        pass  # certifi not installed; proceeds without CA pinning

